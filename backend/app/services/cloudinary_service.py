import cloudinary
import cloudinary.uploader
from app.config import settings

# Configure Cloudinary on import
cloudinary.config(
    cloud_name=settings.CLOUDINARY_CLOUD_NAME,
    api_key=settings.CLOUDINARY_API_KEY,
    api_secret=settings.CLOUDINARY_API_SECRET,
    secure=True,
)


class CloudinaryService:
    """Handles all media uploads to Cloudinary CDN."""

    @staticmethod
    def upload_scan_image(file_bytes: bytes, scan_id: str, panel_type: str = "front") -> str:
        """
        Upload a raw package photo.
        Returns the secure CDN URL.
        """
        response = cloudinary.uploader.upload(
            file_bytes,
            folder=f"metroscan/raw_scans/{scan_id}",
            public_id=f"{panel_type}",
            resource_type="image",
            quality="auto",
            fetch_format="auto",
            overwrite=True,
        )
        return response["secure_url"]

    @staticmethod
    def upload_annotated_image(file_bytes: bytes, scan_id: str, index: int = 0) -> str:
        """
        Upload a bounding-box annotated image (generated by OCR engine).
        Returns the secure CDN URL.
        """
        response = cloudinary.uploader.upload(
            file_bytes,
            folder=f"metroscan/annotated/{scan_id}",
            public_id=f"annotated_{index}",
            resource_type="image",
            quality="auto",
            fetch_format="auto",
            overwrite=True,
        )
        return response["secure_url"]

    @staticmethod
    def upload_report_pdf(pdf_bytes: bytes, scan_id: str) -> str:
        """
        Upload generated PDF inspection certificate / consumer summary.
        Returns the secure CDN URL.
        """
        response = cloudinary.uploader.upload(
            pdf_bytes,
            folder="metroscan/reports",
            public_id=f"report_{scan_id}",
            resource_type="raw",
            overwrite=True,
        )
        return response["secure_url"]
